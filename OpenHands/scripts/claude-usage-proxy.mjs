/**
 * Claude Code / Anthropic Usage Proxy
 *
 * Secure server-side proxy between Grokbot frontend and Anthropic / Claude Code
 * quota and unified rate limit telemetry.
 *
 * Resolves session tokens from request headers, CLAUDE_AUTH_JSON/ANTHROPIC_API_KEY
 * environment secrets, or the host ~/.claude/ files, and caches responses (60s TTL)
 * to prevent excessive polling.
 */

import { request as httpsRequest } from "node:https";
import { readFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";

const CACHE_TTL_MS = 60 * 1000; // 60s cache
const usageCache = new Map(); // tokenHash -> { timestamp, data }

/**
 * Extract token from a raw string or credentials JSON
 */
export function extractClaudeAccessToken(raw) {
  if (!raw || typeof raw !== "string") return null;
  const trimmed = raw.trim();
  if (!trimmed) return null;

  if (trimmed.startsWith("{")) {
    try {
      const parsed = JSON.parse(trimmed);
      if (parsed.tokens?.access_token) return parsed.tokens.access_token;
      if (parsed.access_token) return parsed.access_token;
      if (parsed.accessToken) return parsed.accessToken;
      if (parsed.tokens?.session_token) return parsed.tokens.session_token;
      if (parsed.session_token) return parsed.session_token;
      if (parsed.apiKey) return parsed.apiKey;
      if (parsed.api_key) return parsed.api_key;
      if (parsed.anthropicApiKey) return parsed.anthropicApiKey;
    } catch {
      // Not valid JSON, treat as raw token
    }
  }

  // Handle "Bearer <token>" prefix
  if (trimmed.startsWith("Bearer ")) {
    return trimmed.slice(7).trim();
  }

  return trimmed;
}

/**
 * Extract OAuth access token from the macOS Keychain credential JSON format.
 * Claude Code stores credentials in Keychain as:
 *   { claudeAiOauth: { accessToken: "sk-ant-oat01-...", ... }, ... }
 */
function extractOAuthFromKeychainJSON(raw) {
  if (!raw || typeof raw !== "string") return null;
  try {
    const parsed = JSON.parse(raw.trim());
    const oauth = parsed?.claudeAiOauth;
    if (oauth?.accessToken && typeof oauth.accessToken === "string") {
      return oauth.accessToken;
    }
  } catch {
    // Not the keychain format
  }
  return null;
}

/**
 * Attempt to read token or cached quota from env vars / ~/.claude/ on host
 */
async function getHostClaudeCredentials() {
  // Direct OAuth token (highest priority — the exact format needed for /api/oauth/usage)
  if (process.env.CLAUDE_OAUTH_TOKEN) {
    return { token: process.env.CLAUDE_OAUTH_TOKEN.trim(), source: "oauth_token_env" };
  }

  // Check env vars — also try to extract OAuth token from full keychain JSON
  if (process.env.CLAUDE_AUTH_JSON) {
    const oauthToken = extractOAuthFromKeychainJSON(process.env.CLAUDE_AUTH_JSON);
    if (oauthToken) return { token: oauthToken, source: "env_oauth" };
    const token = extractClaudeAccessToken(process.env.CLAUDE_AUTH_JSON);
    if (token) return { token, source: "env_json" };
  }
  if (process.env.ANTHROPIC_AUTH_JSON) {
    const oauthToken = extractOAuthFromKeychainJSON(process.env.ANTHROPIC_AUTH_JSON);
    if (oauthToken) return { token: oauthToken, source: "env_oauth" };
    const token = extractClaudeAccessToken(process.env.ANTHROPIC_AUTH_JSON);
    if (token) return { token, source: "env_json" };
  }
  if (process.env.ANTHROPIC_API_KEY) {
    const token = extractClaudeAccessToken(process.env.ANTHROPIC_API_KEY);
    if (token) return { token, source: "api_key" };
  }

  const claudeHome = process.env.CLAUDE_HOME || join(homedir(), ".claude");

  // Check quota.json cache generated by local proxy or tool
  try {
    const quotaCachePath = join(claudeHome, "quota.json");
    const quotaRaw = await readFile(quotaCachePath, "utf-8");
    const parsed = JSON.parse(quotaRaw);
    if (parsed && (parsed.fiveHour || parsed.primaryWindow)) {
      return { quotaCache: parsed, source: "quota_json" };
    }
  } catch {
    // Quota cache not found or unreadable
  }

  // Check .credentials.json or credentials.json
  for (const filename of [".credentials.json", "credentials.json", "auth.json"]) {
    try {
      const authPath = join(claudeHome, filename);
      const content = await readFile(authPath, "utf-8");
      const token = extractClaudeAccessToken(content);
      if (token) return { token, source: "credentials_file" };
    } catch {
      // continue
    }
  }

  return null;
}

function normalizeWindow(win) {
  if (!win || typeof win !== "object") return null;

  const limitSeconds =
    Number(
      win.limit_window_seconds ||
        win.window_seconds ||
        win.window ||
        win.seconds ||
        win.limit_seconds ||
        win.limitSeconds,
    ) || 0;

  let rawUsed =
    win.used_percent ??
    win.usedPercent ??
    win.percentage ??
    win.used_percentage ??
    win.consumed_percent ??
    win.utilization;

  let usedPercent = Number(rawUsed) || 0;
  // If given as a 0..1 decimal fraction (e.g. 0.11 instead of 11)
  if (usedPercent > 0 && usedPercent <= 1.0) {
    usedPercent = Math.round(usedPercent * 1000) / 10;
  } else {
    usedPercent = Math.max(0, Math.min(100, Math.round(usedPercent * 10) / 10));
  }

  const remainingPercent = Math.max(
    0,
    Math.min(100, Math.round((100 - usedPercent) * 10) / 10),
  );

  let resetAt =
    Number(
      win.reset_at ||
        win.nextResetTime ||
        win.resetAt ||
        win.resets_at ||
        win.resetTimestamp,
    ) || null;

  // If reset is in milliseconds (e.g. 1724281200000) convert to seconds
  if (resetAt && resetAt > 1e11) {
    resetAt = Math.floor(resetAt / 1000);
  }

  // If relative reset duration is provided
  if (!resetAt) {
    const relSeconds =
      Number(
        win.resets_in_seconds ||
          win.reset_after_seconds ||
          win.resets_in ||
          win.resetsIn,
      ) || 0;
    if (relSeconds > 0) {
      resetAt = Math.floor(Date.now() / 1000) + relSeconds;
    }
  }

  const limitReached = Boolean(
    win.limit_reached || win.limitReached || usedPercent >= 100,
  );

  return {
    limitSeconds,
    usedPercent,
    remainingPercent,
    resetAt,
    limitReached,
  };
}

/**
 * Normalize Claude / Anthropic quota payload into structured quota data
 */
export function normalizeClaudeUsage(data) {
  if (!data || typeof data !== "object") {
    return null;
  }

  const planType =
    typeof data.plan_type === "string"
      ? data.plan_type
      : typeof data.plan === "string"
        ? data.plan
        : typeof data.planType === "string"
          ? data.planType
          : "Claude Pro";

  let primaryWindow = null;
  let secondaryWindow = null;

  // Check fiveHour / sevenDay structure
  if (data.fiveHour || data.five_hour) {
    const raw5h = data.fiveHour || data.five_hour;
    primaryWindow = normalizeWindow({
      limit_window_seconds: 18000,
      used_percent:
        raw5h.usedPercent ??
        raw5h.used_percent ??
        (raw5h.utilization !== undefined ? raw5h.utilization * 100 : undefined),
      reset_at: raw5h.resetTimestamp ?? raw5h.reset_at ?? raw5h.resetAt,
      limit_reached: raw5h.limitReached,
    });
  }

  if (data.sevenDay || data.seven_day) {
    const raw7d = data.sevenDay || data.seven_day;
    secondaryWindow = normalizeWindow({
      limit_window_seconds: 604800,
      used_percent:
        raw7d.usedPercent ??
        raw7d.used_percent ??
        (raw7d.utilization !== undefined ? raw7d.utilization * 100 : undefined),
      reset_at: raw7d.resetTimestamp ?? raw7d.reset_at ?? raw7d.resetAt,
      limit_reached: raw7d.limitReached,
    });
  }

  // Check rate_limit / primary_window
  if (!primaryWindow && data.primaryWindow) {
    primaryWindow = normalizeWindow(data.primaryWindow);
  }
  if (!secondaryWindow && data.secondaryWindow) {
    secondaryWindow = normalizeWindow(data.secondaryWindow);
  }
  if (!primaryWindow && data.rate_limit?.primary_window) {
    primaryWindow = normalizeWindow(data.rate_limit.primary_window);
  }
  if (!secondaryWindow && data.rate_limit?.secondary_window) {
    secondaryWindow = normalizeWindow(data.rate_limit.secondary_window);
  }

  return {
    provider: "claude",
    planType,
    primaryWindow,
    secondaryWindow,
    updatedAt: Math.floor(Date.now() / 1000),
  };
}

/**
 * Handle HTTP requests to /api/observability/claude/usage
 */
export async function handleClaudeUsageProxy(req, res, pathname, query = {}) {
  // CORS / methods
  if (req.method === "OPTIONS") {
    res.writeHead(204, {
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
      "Access-Control-Allow-Headers":
        "Content-Type, Authorization, X-Claude-Token, X-Anthropic-Key",
    });
    res.end();
    return;
  }

  if (req.method !== "GET" && req.method !== "POST") {
    res.writeHead(405, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ error: "Method not allowed" }));
    return;
  }

  // Resolve token from request headers or body or query or host
  let token = null;

  const authHeader =
    req.headers["authorization"] ||
    req.headers["x-claude-token"] ||
    req.headers["x-anthropic-key"];
  if (authHeader) {
    token = extractClaudeAccessToken(authHeader);
  }

  if (!token && query.token) {
    token = extractClaudeAccessToken(query.token);
  }

  // If not in headers/query and POST request, check body
  if (!token && req.method === "POST") {
    const chunks = [];
    for await (const chunk of req) {
      chunks.push(chunk);
    }
    const bodyStr = Buffer.concat(chunks).toString("utf8");
    token = extractClaudeAccessToken(bodyStr);
  }

  let hostCreds = null;
  if (!token) {
    hostCreds = await getHostClaudeCredentials();
    if (hostCreds?.token) {
      token = hostCreds.token;
    }
  }

  // If we have cached quota directly from host
  if (hostCreds?.quotaCache) {
    const normalized = normalizeClaudeUsage(hostCreds.quotaCache);
    if (normalized) {
      res.writeHead(200, {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
      });
      res.end(JSON.stringify(normalized));
      return;
    }
  }

  if (!token) {
    // CRITICAL: Do NOT return fake "100% available" defaults.
    // Returning a fake positive is worse than returning nothing — it makes
    // the user think they have quota when they might be completely exhausted.
    // Return 503 so the fuel gauge shows "Unknown" instead of a green lie.
    res.writeHead(503, {
      "Content-Type": "application/json",
      "Access-Control-Allow-Origin": "*",
    });
    res.end(
      JSON.stringify({
        error: "no_credentials",
        message:
          "No Claude token found. Cannot verify quota. Set CLAUDE_AUTH_JSON or ANTHROPIC_API_KEY.",
      }),
    );
    return;
  }

  const tokenHash = createHash("sha256").update(token).digest("hex");
  const cached = usageCache.get(tokenHash);
  const now = Date.now();

  const bypassCache = query.refresh === "true" || query.refresh === "1";

  if (!bypassCache && cached && now - cached.timestamp < CACHE_TTL_MS) {
    res.writeHead(200, {
      "Content-Type": "application/json",
      "Access-Control-Allow-Origin": "*",
      "X-Cache": "HIT",
    });
    res.end(JSON.stringify(cached.data));
    return;
  }

  // -------------------------------------------------------------------
  // REAL API CALL: OAuth tokens (sk-ant-oat*) can call the dedicated
  // usage endpoint at api.anthropic.com/api/oauth/usage — the same
  // endpoint that Claude Code CLI uses for /usage.
  // -------------------------------------------------------------------
  const isOAuthToken = token.startsWith("sk-ant-oat");
  let oauthError = null;

  if (isOAuthToken) {
    try {
      const utilization = await fetchOAuthUsage(token);
      if (utilization) {
        const quotaResult = normalizeOAuthUsage(utilization);

        usageCache.set(tokenHash, { timestamp: now, data: quotaResult });

        res.writeHead(200, {
          "Content-Type": "application/json",
          "Access-Control-Allow-Origin": "*",
          "X-Cache": "MISS",
          "X-Source": "oauth-api",
        });
        res.end(JSON.stringify(quotaResult));
        return;
      }
    } catch (err) {
      console.error("[claude-proxy] OAuth usage API error:", err.message);
      // Detect token expiry (401) vs other failures and surface a specific message
      oauthError = err.message || "Unknown error";
      // Fall through to unverified with specific error
    }
  }

  // -------------------------------------------------------------------
  // FALLBACK: Non-OAuth token (API key), OAuth API call failed, or
  // token expired. Show a specific warning so the user knows WHY.
  // -------------------------------------------------------------------
  let warning;
  if (oauthError && oauthError.includes("401")) {
    warning =
      "⛽ Claude OAuth token EXPIRED — fuel gauge data is stale. Run `claude auth login` to refresh, then update CLAUDE_OAUTH_TOKEN in Coolify.";
  } else if (oauthError) {
    warning = `⛽ Claude usage API failed: ${oauthError}. Data may be stale.`;
  } else if (!isOAuthToken && token.startsWith("sk-ant-api")) {
    warning =
      "API keys cannot check subscription quota. Use an OAuth token (from Claude Code) for real usage data.";
  } else {
    warning =
      "Token found but quota cannot be verified via API. Check claude.ai/settings for real usage.";
  }

  const quotaResult = {
    provider: "claude",
    planType: token.startsWith("sk-ant-") ? "Claude API" : "Claude Pro",
    unverified: true,
    primaryWindow: null,
    secondaryWindow: null,
    updatedAt: Math.floor(Date.now() / 1000),
    warning,
  };

  res.writeHead(200, {
    "Content-Type": "application/json",
    "Access-Control-Allow-Origin": "*",
    "X-Cache": "MISS",
    "X-Unverified": "true",
  });
  res.end(JSON.stringify(quotaResult));
}

// -------------------------------------------------------------------
// fetchOAuthUsage — calls the real Anthropic OAuth usage endpoint.
// This is the same endpoint Claude Code CLI uses for /usage.
// GET https://api.anthropic.com/api/oauth/usage
// Authorization: Bearer <oauth_token>
// -------------------------------------------------------------------
async function fetchOAuthUsage(oauthToken) {
  return new Promise((resolve, reject) => {
    const options = {
      hostname: "api.anthropic.com",
      port: 443,
      path: "/api/oauth/usage",
      method: "GET",
      headers: {
        Authorization: `Bearer ${oauthToken}`,
        "Content-Type": "application/json",
        "User-Agent": "grokbot-fuel-gauge/1.0",
      },
      timeout: 8000,
    };

    const req = httpsRequest(options, (resp) => {
      const chunks = [];
      resp.on("data", (chunk) => chunks.push(chunk));
      resp.on("end", () => {
        const body = Buffer.concat(chunks).toString("utf8");
        if (resp.statusCode !== 200) {
          reject(new Error(`OAuth usage API returned ${resp.statusCode}: ${body.slice(0, 200)}`));
          return;
        }
        try {
          resolve(JSON.parse(body));
        } catch (e) {
          reject(new Error(`Failed to parse OAuth usage response: ${e.message}`));
        }
      });
    });

    req.on("error", reject);
    req.on("timeout", () => {
      req.destroy();
      reject(new Error("OAuth usage API timed out"));
    });
    req.end();
  });
}

// -------------------------------------------------------------------
// normalizeOAuthUsage — converts the raw /api/oauth/usage response
// into the normalized format the fuel gauge frontend expects.
//
// Input shape (from Anthropic):
//   five_hour:    { utilization: 0.0, resets_at: "..." }
//   seven_day:    { utilization: 21.0, resets_at: "..." }
//   extra_usage:  { is_enabled, used_credits, monthly_limit, utilization }
//   limits:       [{ kind, percent, severity, resets_at }]
//   spend:        { percent, severity, used, limit }
// -------------------------------------------------------------------
function normalizeOAuthUsage(data) {
  let primaryWindow = null;
  let secondaryWindow = null;

  // --- 5-hour session window ---
  const fiveHour = data.five_hour;
  if (fiveHour && fiveHour.utilization !== undefined) {
    const usedPercent = Math.max(0, Math.min(100, Math.round(fiveHour.utilization * 10) / 10));
    const resetAt = fiveHour.resets_at
      ? Math.floor(new Date(fiveHour.resets_at).getTime() / 1000)
      : null;
    primaryWindow = {
      limitSeconds: 18000,
      usedPercent,
      remainingPercent: Math.round((100 - usedPercent) * 10) / 10,
      resetAt,
      limitReached: usedPercent >= 100,
    };
  }

  // --- Weekly window ---
  const sevenDay = data.seven_day;
  if (sevenDay && sevenDay.utilization !== undefined) {
    const usedPercent = Math.max(0, Math.min(100, Math.round(sevenDay.utilization * 10) / 10));
    const resetAt = sevenDay.resets_at
      ? Math.floor(new Date(sevenDay.resets_at).getTime() / 1000)
      : null;
    secondaryWindow = {
      limitSeconds: 604800,
      usedPercent,
      remainingPercent: Math.round((100 - usedPercent) * 10) / 10,
      resetAt,
      limitReached: usedPercent >= 100,
    };
  }

  // --- Extra usage / spend credits ---
  let extraUsage = null;
  if (data.extra_usage && data.extra_usage.is_enabled) {
    extraUsage = {
      enabled: true,
      usedCredits: data.extra_usage.used_credits ?? 0,
      monthlyLimit: data.extra_usage.monthly_limit ?? 0,
      utilization: data.extra_usage.utilization ?? 0,
      currency: data.extra_usage.currency ?? "USD",
      decimalPlaces: data.extra_usage.decimal_places ?? 2,
    };
  }

  // --- Spend summary ---
  let spend = null;
  if (data.spend) {
    spend = {
      percent: data.spend.percent ?? 0,
      severity: data.spend.severity ?? "normal",
      enabled: data.spend.enabled ?? false,
      usedMinor: data.spend.used?.amount_minor ?? 0,
      limitMinor: data.spend.limit?.amount_minor ?? 0,
      currency: data.spend.used?.currency ?? "USD",
      exponent: data.spend.used?.exponent ?? 2,
    };
  }

  return {
    provider: "claude",
    planType: "Claude Pro",
    primaryWindow,
    secondaryWindow,
    extraUsage,
    spend,
    updatedAt: Math.floor(Date.now() / 1000),
  };
}

